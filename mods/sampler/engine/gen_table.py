"""Write interp_table.c: the 6-tap, 256-phase interpolation table of the SAMPLER and an exp2 table.

Kernel: two windowed sincs (Kaiser window), five parameters fitted to the frequency response of the
Digitakt's interpolator measured in the emulator (gain within 0.1 dB up to 0.55 x the sample rate,
same stop band to -60 dB). The coefficients are computed here; no table is taken from the Digitakt.

    h(x) = ((1 + G) FC sinc(FC x) - G FC2 sinc(FC2 x)) * kaiser(BETA, x / HALF)

Tap k of phase p sits at x = (k - 2) - (p + 4) / 256, the Digitakt's alignment (output a little after
tap 2). Scale: each phase sums to about 13256 (the Digitakt's level before the half-band filter).
"""

import math
from pathlib import Path

FC, FC2, G, BETA, HALF = 0.68262765, 0.24967796, 3.1292778, 6.92082211, 3.07817379
SUM = 13256


def i0(x: float) -> float:
    s, t, k = 1.0, 1.0, 1
    while t > 1e-17 * s:
        t *= (x / (2 * k)) ** 2
        s += t
        k += 1
    return s


def sinc(x: float) -> float:
    return 1.0 if x == 0 else math.sin(math.pi * x) / (math.pi * x)


def h(x: float) -> float:
    r = x / HALF
    if abs(r) >= 1:
        return 0.0
    w = i0(BETA * math.sqrt(1 - r * r)) / i0(BETA)
    return ((1 + G) * FC * sinc(FC * x) - G * FC2 * sinc(FC2 * x)) * w


def table() -> list[list[list[int]]]:
    raw = [[h((k - 2) - (p + 4) / 256) for k in range(6)] for p in range(256)]
    scale = SUM * 256 / sum(sum(r) for r in raw)
    t = [[[0, 0] for _ in range(256)] for _ in range(3)]
    for p, r in enumerate(raw):
        for k in range(6):
            t[k // 2][p][k % 2] = round(r[k] * scale)
    return t


def main() -> None:
    t = table()
    lines = ["/* Generated by gen_table.py. */", '#include "sampler.h"', "",
             "const int16_t sm_interp_table[3][256][2] = {"]
    for row in t:
        lines.append("    {")
        for p in range(0, 256, 6):
            lines.append("        " + " ".join(f"{{{a}, {b}}}," for a, b in row[p:p + 6]))
        lines.append("    },")
    lines.append("};")
    lines += ["", "/* 2^(i / 256) in Q30, i = 0..256 */", "const uint32_t sm_exp2_q30[257] = {"]
    e = [round(2 ** (i / 256) * (1 << 30)) for i in range(257)]
    for k in range(0, 257, 6):
        lines.append("    " + " ".join(f"{v}u," for v in e[k:k + 6]))
    lines.append("};")
    Path(__file__).with_name("interp_table.c").write_text("\n".join(lines) + "\n", encoding="ascii")


if __name__ == "__main__":
    main()
