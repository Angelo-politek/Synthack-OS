"""Genera mods/about/patch.json e mods/about/about_data.h (vedi about.c).

    python mods/about/make_patch.py       # richiede gcc m68k in WSL (CONTRIBUTING.md)

about_data.h: le righe dell'elenco. Versione dallo splash (mods/splash/make_patch.py), una riga per ogni mod
`feature` o `machine` del repo con il suo stato (mod.json) e l'indirizzo dei suoi primi byte nell'area mod
(registro): a zero se la mod non e' nella build, e la riga non si mostra. Va rigenerato quando si aggiunge una mod
o cambia uno stato o la versione (tests/test_about.py lo controlla).
"""

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO / "tools" / "build"))
import modarea_layout  # noqa: E402
import modkit  # noqa: E402
import registry  # noqa: E402

SLOT = next(s for s, who in registry.SFCORE_SLOTS.items() if who == "about")
SITE, SITE_ORIG = 0x4005_F176, "205248780002"        # movea.l (a2),a0 ; pea 2.w: dopo l'ultima riga del menu
WIDTH = 31                                            # caratteri per riga (font 4x6)
CREDITS = ["RXUTING: SY FM4", "GSM1980: SYNFACT", "IRPINA: ELEKLOADER", "M. BIERLING: FIRMWARE TOOL",
           "A. GRECHKIN: COMPRESSOR IDS"]


def version() -> str:
    text = (REPO / "mods" / "splash" / "make_patch.py").read_text(encoding="utf-8")
    return re.search(r'VERSION = "smslant", "v([^"]+)"', text).group(1)


def rows() -> list[tuple[str, int]]:
    """(testo, indirizzo da guardare o 0)."""
    out = [(f"SYNTHACK OS {version()}", 0), ("FOR SYNTAKT OS 1.42", 0), ("NOT AFFILIATED WITH ELEKTRON", 0),
           ("", 0), ("- MODS IN THIS BUILD -", 0)]
    for d in sorted((REPO / "mods").glob("*/mod.json")):
        card = json.loads(d.read_text(encoding="utf-8"))
        name = d.parent.name
        if card["kind"] not in ("feature", "machine") or name == "about" or not (d.parent / "patch.json").exists():
            continue
        first = min((a for a, _, who, _ in registry.MODAREA if who == name), default=None)
        if first is None:
            continue
        status = {"stable": "", "beta": "BETA", "experimental": "EXP"}[card["status"]]
        tail = f" ({status})" if status else ""            # font proporzionale: niente colonne
        out.append((card["title"].upper()[:WIDTH - len(tail)] + tail, modarea_layout.RAM + first))
    out += [("", 0), ("- SOURCE -", 0), ("GITHUB.COM/ANGELO-POLITEK/", 0), ("SYNTHACK-OS", 0), ("GPL-2.0-OR-LATER", 0),
            ("", 0), ("- CREDITS -", 0), *((c, 0) for c in CREDITS)]
    assert all(len(t) <= WIDTH and t.isascii() and '"' not in t and "\\" not in t for t, _ in out), out
    return out


def smgr_row() -> int:
    """Indirizzo delle quattro callback della riga SAMPLES di mods/sample-manager, 0 se quella mod non c'e'."""
    f = REPO / "mods" / "sample-manager" / "patch.json"
    return int(json.loads(f.read_text(encoding="utf-8"))["symbols"]["smgr_row"], 16) if f.exists() else 0


def header() -> str:
    r = rows()
    body = "\n".join(f'    {{"{t}", {p:#x}u}},' for t, p in r)
    return ("/* Generated by make_patch.py: do not edit. */\n"
            f"#define ROWS {len(r)}\nstatic const struct row rows[ROWS] = {{\n{body}\n}};\n")


def main() -> None:
    (HERE / "about_data.h").write_text(header(), encoding="utf-8", newline="\n")
    m = modkit.Mod(__file__)
    code = m.compile(["about.c"], defs={"SMGR_ROW": smgr_row()})
    m.area(code, "about.c")
    m.word(registry.SFCORE_TABLE + 4 * SLOT, code["about_module"], f"tabella dei moduli di sfcore, posto {SLOT}")
    m.hook(SITE, SITE_ORIG, code["about_settings"], "menu delle impostazioni: la riga SYNTHACK dopo l'ultima")
    m.write(description="Riga SYNTHACK in fondo al menu delle impostazioni: versione, mod nella build con lo stato, "
                        "repository, crediti. Aggancio e MenuItem come Synfact (core/settings.s).",
            requires=["modarea", "sfcore"], license="GPL-2.0-or-later",
            credits="Synfact (GSM1980), elekloader (irpina)",
            symbols={k: v for k, v in sorted(code.items()) if k.startswith("about_")})


if __name__ == "__main__":
    main()
