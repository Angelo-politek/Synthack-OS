"""Write fm4_tables.c: the Q1.15 sine table, 1024 points plus a guard."""
import math
N = 1024
vals = [round(32767 * math.sin(2 * math.pi * i / N)) for i in range(N + 1)]
lines = ['/* Generated by gen_tables.py. */', '#include "fm4.h"', '',
         'const int16_t fm4_sine[(1 << FM4_SINE_BITS) + 1] = {']
for k in range(0, len(vals), 12):
    lines.append('    ' + ', '.join(str(v) for v in vals[k:k + 12]) + ',')
lines.append('};')
open('fm4_tables.c', 'w').write('\n'.join(lines) + '\n')
