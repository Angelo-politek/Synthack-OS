"""Write fm4_syn_tables.c: per-block decay factors and 2^(i/256) for DET."""
import math
BLOCKS_PER_S = 48000 / 32
lines = ['/* Generated by gen_syn_tables.py. */', '#include <stdint.h>', '',
         'const int32_t fm4_decay_k[128] = {']
vals = []
for v in range(128):
    if v == 127:
        k = 1.0                                   # hold
    else:
        t = 0.003 * (12 / 0.003) ** (v / 126)     # seconds to -60 dB
        k = 10 ** (-3 / (BLOCKS_PER_S * t))
    vals.append(min(0x7fffffff, int(round(k * 2 ** 31))))
for i in range(0, 128, 6):
    lines.append('    ' + ', '.join('%d' % x for x in vals[i:i + 6]) + ',')
lines.append('};')
lines += ['', '/* 2^(i/256), Q16.16, i = 0..256 */', 'const uint32_t fm4_exp2_q16[257] = {']
ex = [int(round(2 ** (i / 256) * 65536)) for i in range(257)]
for i in range(0, 257, 8):
    lines.append('    ' + ', '.join('%d' % x for x in ex[i:i + 8]) + ',')
lines.append('};')
open('fm4_syn_tables.c', 'w').write('\n'.join(lines) + '\n')
